/* Writes a C file that holds the bytes of the domain file.
   Usage: tcc -run gen/embed.c domain/domain.lang build/domain.c [NAME]
   NAME is the array symbol (default domain_source); NAME_len holds the
   byte count. SHARED by the tcc kits. */
#include <stdio.h>

static int embed(const char *name, const char *sym, FILE *in, FILE *out) {
  fprintf(out, "/* Generated by gen/embed.c from %s. Do not edit. */\n", name);
  fprintf(out, "#include <stddef.h>\n\nconst unsigned char %s[] = {", sym);
  size_t count = 0;
  int c = fgetc(in);
  while (c != EOF) {
    fprintf(out, "%s0x%02x,", count % 12 == 0 ? "\n  " : " ", (unsigned)c);
    count++;
    c = fgetc(in);
  }
  fprintf(out, "\n  0x00\n};\nconst size_t %s_len = %lu;\n", sym, (unsigned long)count);
  return ferror(in) == 0 && ferror(out) == 0;
}

int main(int argc, char **argv) {
  if (argc != 3 && argc != 4) {
    fputs("usage: embed IN OUT [NAME]\n", stderr);
    return 2;
  }
  FILE *in = fopen(argv[1], "rb");
  FILE *out = in == NULL ? NULL : fopen(argv[2], "wb");
  const char *sym = argc == 4 ? argv[3] : "domain_source";
  int ok = out != NULL && embed(argv[1], sym, in, out);
  if (in != NULL) fclose(in);
  if (out != NULL) ok = fclose(out) == 0 && ok;
  if (!ok) fprintf(stderr, "embed: cannot copy %s to %s\n", argv[1], argv[2]);
  return ok ? 0 : 2;
}
