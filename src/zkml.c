/* langc zkml (docs/PLAN.md 5.3, 5.4). Each signer NAME ARGS k is a leaf-lang
   Signer value: pk = pack root (pack pubSeed (pack n (pack logW h))), then m,
   then sig = pack index (pack rand (pack wots auth)). The writer prints its
   flat words (root, pubSeed, n, logw, h, m, index, rand, 67 x 4 wots words,
   h x 4 auth words) as data defs under a parameter z: each word is
   `natAdd z w`. The output is the constants defs, the fixed text
   zkml/xmss.lang, the data defs and the entry zkAggregate. */
#include <inttypes.h>
#include <stdio.h>
#include <string.h>

#include "front/check.h"
#include "front/poseidon2.h"
#include "zkml.h"

extern const unsigned char zkml_source[];
extern const size_t zkml_source_len;

#define ZKML_WOTS_LEN 67u
#define ZKML_HEIGHT_MAX 64u

typedef struct {
  Machine *m;
  FILE *out;
  const Value *fin_at; /* the def value of finAt (domain.lang) */
  uint32_t open;       /* the cons cells to close */
  int ok;
} Writer;

static uint32_t def_named(const Machine *m, const char *name) {
  uint32_t i;
  for (i = 0; i < m->def_count; i++)
    if (strcmp(m->defs[i].name, name) == 0) return i;
  return m->def_count;
}

/* part v i: field i of the pack v, or NULL. */
static const Value *part(const Value *v, uint32_t i) {
  return v != NULL && v->kind == VAL_OP && v->op == OP_PACK && v->argc == 2 ? v->args[i] : NULL;
}

static const Value *apply_or_null(Machine *m, const Value *fn, const Value *arg) {
  return fn == NULL || arg == NULL ? NULL : apply_value(m, fn, arg);
}

/* logw_nat m v: the bits of the closed LogW v (1, 2, 4 or 8) as a Nat, or
   NULL. logWBits is a primitive op (OP_LOGW_BITS), not a def: this is the
   map of logw_bits (front/eval.c). */
static const Value *logw_nat(Machine *m, const Value *v) {
  if (v == NULL || v->kind != VAL_OP || v->argc != 0) return NULL;
  if (v->op == OP_LOGW1) return val_nat(m, 1);
  if (v->op == OP_LOGW2) return val_nat(m, 2);
  if (v->op == OP_LOGW4) return val_nat(m, 4);
  return v->op == OP_LOGW8 ? val_nat(m, 8) : NULL;
}

static void word(Writer *w, const Value *v) {
  if (v == NULL || v->kind != VAL_NAT) {
    w->ok = 0;
    return;
  }
  fprintf(w->out, "cons (natAdd z %" PRIu64 ") (", v->nat);
  w->open++;
}

static void digest_words(Writer *w, const Value *v) {
  uint32_t i;
  if (v == NULL || v->kind != VAL_OP || v->op != OP_DIGEST_VAL || v->argc != 4) {
    w->ok = 0;
    return;
  }
  for (i = 0; i < 4; i++) word(w, v->args[i]);
}

/* fin_elem f n d k: finAt A n f d k. A is not read by eval. */
static const Value *fin_elem(Writer *w, const Value *f, uint64_t n, const Value *d, uint64_t k) {
  const Value *v = apply_or_null(w->m, w->fin_at, val_univ(w->m, 0));
  v = apply_or_null(w->m, v, val_nat(w->m, n));
  v = apply_or_null(w->m, v, f);
  v = apply_or_null(w->m, v, d);
  return apply_or_null(w->m, v, val_nat(w->m, k));
}

static void signer_words(Writer *w, const Value *e) {
  const Value *pk = part(e, 0), *sig = part(part(e, 1), 1);
  const Value *root = part(pk, 0), *params = part(part(pk, 1), 1);
  const Value *h = part(part(params, 1), 1);
  const Value *rest = part(part(sig, 1), 1);
  uint64_t i;
  int h_ok = h != NULL && h->kind == VAL_NAT && h->nat <= ZKML_HEIGHT_MAX;
  if (!h_ok || rest == NULL) {
    w->ok = 0;
    return;
  }
  digest_words(w, root);
  digest_words(w, part(part(pk, 1), 0));
  word(w, part(params, 0));
  word(w, logw_nat(w->m, part(part(params, 1), 0)));
  word(w, h);
  digest_words(w, part(part(e, 1), 0));
  word(w, part(sig, 0));
  digest_words(w, part(part(sig, 1), 0));
  for (i = 0; i < ZKML_WOTS_LEN && w->ok; i++) digest_words(w, fin_elem(w, part(rest, 0), ZKML_WOTS_LEN, root, i));
  for (i = 0; i < h->nat && w->ok; i++) digest_words(w, fin_elem(w, part(rest, 1), h->nat, root, i));
}

static void close_list(Writer *w) {
  fputs("nil", w->out);
  for (; w->open > 0; w->open--) fputc(')', w->out);
  fputc('\n', w->out);
}

static void const_list(FILE *out, const uint32_t *v, unsigned n) {
  unsigned i;
  for (i = 0; i < n; i++) fprintf(out, "cons %u (", v[i]);
  fputs("nil", out);
  for (i = 0; i < n; i++) fputc(')', out);
}

static void const_rows(FILE *out, const char *name, const uint32_t rc[POSEIDON2_HALF_F][POSEIDON2_WIDTH]) {
  unsigned r;
  fprintf(out, "def %s : List (List Nat) := ", name);
  for (r = 0; r < POSEIDON2_HALF_F; r++) {
    fputs("cons (", out);
    const_list(out, rc[r], POSEIDON2_WIDTH);
    fputs(") (", out);
  }
  fputs("nil", out);
  for (r = 0; r < POSEIDON2_HALF_F; r++) fputc(')', out);
  fputc('\n', out);
}

static void write_head(FILE *out, const char *name, unsigned count) {
  fprintf(out, "-- Generated by langc zkml from %s, %u signers. Do not edit.\n", name, count);
  fputs("-- The Poseidon2 constants (poseidon2_babybear16, canonical values).\n", out);
  const_rows(out, "p2RcInit", poseidon2_babybear16.initial);
  const_rows(out, "p2RcTerm", poseidon2_babybear16.terminal);
  fputs("def p2RcInt : List Nat := ", out);
  const_list(out, poseidon2_babybear16.internal, POSEIDON2_ROUNDS_P);
  fputs("\n\n", out);
  fwrite(zkml_source, 1, zkml_source_len, out);
  fputs("\n-- The data defs: the flat words of each signer under z.\n", out);
}

static int parse_nat(const char *text, uint64_t *out) {
  uint64_t n = 0;
  size_t i;
  for (i = 0; text[i] >= '0' && text[i] <= '9' && i < 19; i++) n = n * 10 + (uint64_t)(text[i] - '0');
  *out = n;
  return i > 0 && text[i] == '\0';
}

static const Value *signer_value(Machine *m, uint32_t d, char *const *args, int arg_count, uint64_t k) {
  const Value *v = def_value(m, d);
  uint64_t n = 0;
  int i;
  for (i = 0; i < arg_count && v != NULL; i++) v = parse_nat(args[i], &n) ? apply_value(m, v, val_nat(m, n)) : NULL;
  return apply_or_null(m, v, val_nat(m, k));
}

/* Check the applications under HASH_NONE, before evaluating or opening OUT.
   Runtime values erase binder types, so inspecting the packs is not enough. */
static int signer_type(Machine *m, uint32_t d, char *const *args, int arg_count, unsigned count) {
  const Value *t = m->defs[d].type;
  uint32_t signer = def_named(m, "Signer");
  uint64_t n = 0;
  int i;
  unsigned k;
  for (i = 0; i < arg_count; i++) {
    if (t == NULL || t->kind != VAL_PI || !val_is(t->dom, OP_NAT)) return 0;
    if (!parse_nat(args[i], &n)) return 0;
    t = closure_apply(m, t, val_nat(m, n));
  }
  if (t == NULL || t->kind != VAL_PI || !val_is(t->dom, OP_NAT) || signer == m->def_count) return 0;
  for (k = 0; k < count; k++)
    if (!conv_values(m, 0, closure_apply(m, t, val_nat(m, k)), def_value(m, signer))) return 0;
  return 1;
}

int zkml_command(Machine *m, const char *name, char *const *args, int arg_count, unsigned count,
                 const char *out_path) {
  uint32_t d = def_named(m, name), fin = def_named(m, "finAt");
  uint64_t n = 0;
  unsigned k;
  int i;
  Writer w;
  m->def = name;
  if (d == m->def_count) return diag_fail(m->diag, "EVAL_ENTRY", name, "no definition has this name") + 1;
  if (fin == m->def_count) return diag_fail(m->diag, "EVAL_ENTRY", name, "no definition finAt in the prelude") + 1;
  for (i = 0; i < arg_count; i++)
    if (!parse_nat(args[i], &n)) return diag_fail(m->diag, "USAGE", name, "the zkml argument '%s' is not a Nat", args[i]) + 2;
  if (!signer_type(m, d, args, arg_count, count))
    return diag_fail(m->diag, "USAGE", name, "zkml needs Nat arguments followed by a Nat index and a Signer result") + 2;
  /* The hash ops compute only under a binding (Q-S4-3 (a)): drop the values
     that check computed while they were stuck, as eval_command does. */
  m->hash = HASH_POSEIDON2;
  for (k = 0; k < m->def_count; k++) m->defs[k].value = NULL;
  w.m = m;
  w.fin_at = def_value(m, fin);
  w.open = 0;
  w.ok = w.fin_at != NULL;
  w.out = fopen(out_path, "wb");
  if (w.out == NULL) return diag_fail(m->diag, "IO", NULL, "cannot write '%s'", out_path) + 2;
  write_head(w.out, name, count);
  for (k = 0; k < count && w.ok; k++) {
    fprintf(w.out, "def zkSigner%u : Nat -> List Nat := fun z => ", k);
    signer_words(&w, signer_value(m, d, args, arg_count, k));
    close_list(&w);
  }
  fputs("def zkSigners : Nat -> List (List Nat) := fun z => ", w.out);
  for (k = 0; k < count; k++) fprintf(w.out, "cons (zkSigner%u z) (", k);
  fputs("nil", w.out);
  for (k = 0; k < count; k++) fputc(')', w.out);
  fputs("\ndef zkAggregate : Nat -> Nat := fun z => aggregate (zkSigners z)\n", w.out);
  if (fclose(w.out) != 0) return diag_fail(m->diag, "IO", NULL, "cannot write '%s'", out_path) + 2;
  return w.ok ? 0 : diag_fail(m->diag, "EVAL_PRINT", name, "the value is not a signer of closed words") + 1;
}
